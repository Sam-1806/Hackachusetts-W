"""Write handoff/person3_demo/demoContext.real.ts from sim_ranks_values.json and preview the UI totals.

The UI (sim+ranks personOneRanking.ts) scores: flood 0-30 (share of loaded USGS 2018 events whose
footprint intersects the corridor's fixture road) + accessPoints + propertyPoints.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from shapely.geometry import LineString, shape

ROOT = Path(__file__).resolve().parents[2]
HAND = ROOT / "handoff" / "person3_demo"


def main() -> None:
    sim = Path(sys.argv[1]) / "frontend" / "public" / "data"
    vals = json.loads((HAND / "sim_ranks_values.json").read_text(encoding="utf-8"))
    ctx = vals["DEMO_CONTEXT"]

    # Same corridor -> fixture roads mapping the sim+ranks loader builds.
    roads = {}
    for f in json.loads((sim / "morrissey_roads.geojson").read_text(encoding="utf-8"))["features"]:
        roads.setdefault(f["properties"]["corridor_id"], []).append(LineString(f["geometry"]["coordinates"]))
    for f in json.loads((sim / "app-dataset.json").read_text(encoding="utf-8"))["exposure"]["roads_geojson"]["features"]:
        rid = f["properties"]["road_id"]
        if rid in ("fixture-road-day", "fixture-road-mount-vernon"):
            cid = "fixture:day-boulevard" if rid == "fixture-road-day" else "fixture:mount-vernon"
            roads.setdefault(cid, []).append(LineString(f["geometry"]["coordinates"]))
    events = [[shape(p["geometry"]) for p in json.loads((sim / n).read_text(encoding="utf-8"))["features"]]
              for n in ("usgs_2018_01_04_morrissey.geojson", "usgs_2018_03_02_morrissey.geojson")]

    print("UI preview (flood + access + property = total):")
    rows = []
    for cid, v in ctx.items():
        hits = sum(1 for ev in events if any(r.intersects(p) for r in roads.get(cid, []) for p in ev))
        flood = round(hits / len(events) * 30)
        rows.append((flood + v["accessPoints"] + v["propertyPoints"], cid, flood, v))
    for i, (tot, cid, flood, v) in enumerate(sorted(rows, key=lambda r: -r[0]), 1):
        print(f"  #{i} {cid:30} {flood:>2} + {v['accessPoints']:>2} + {v['propertyPoints']:>2} = {tot}")

    body = ",\n".join(
        f"  {json.dumps(cid)}: {{\n"
        f"    accessPoints: {v['accessPoints']},\n"
        f"    propertyPoints: {v['propertyPoints']},\n"
        f"    accessNote:\n      {json.dumps(v['accessNote'], ensure_ascii=False)},\n"
        f"    propertyNote:\n      {json.dumps(v['propertyNote'], ensure_ascii=False)},\n"
        f"  }}" for cid, v in ctx.items())
    ts = (
        "// Generated by engineering/scripts/emit_demo_context_ts.py from sim_ranks_values.json.\n"
        f"// Computed {vals['generated_at']} on {vals['graph_version']}. Replaces the illustrative DEMO_CONTEXT in\n"
        "// frontend/src/data/personOneRanking.ts (sim+ranks). Points keep the UI's weights (access 45, property 25),\n"
        "// scaled to the max among these four corridors. See sim_ranks_values.json for raw values and limitations.\n"
        "export const REAL_CONTEXT: Record<string, {\n"
        "  accessPoints: number;\n  propertyPoints: number;\n  accessNote: string;\n  propertyNote: string;\n"
        "}> = {\n" + body + ",\n};\n"
    )
    (HAND / "demoContext.real.ts").write_text(ts, encoding="utf-8")
    print(f"wrote {HAND / 'demoContext.real.ts'}")


if __name__ == "__main__":
    main()
